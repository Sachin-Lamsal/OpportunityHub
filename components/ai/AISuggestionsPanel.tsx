"use client";

import { useState, useTransition } from "react";
import Link from "next/link";
import { getAISuggestions, type AIActionResult } from "@/lib/actions/ai";
import type { AISuggestionResult } from "@/lib/ai/prompts";
import Button from "@/components/ui/Button";
import { Card } from "@/components/ui/Card";
import AITokenBadge from "@/components/ai/AITokenBadge";

interface AISuggestionsPanelProps {
  compact?: boolean;
}

export default function AISuggestionsPanel({ compact = false }: AISuggestionsPanelProps) {
  const [result, setResult] = useState<AIActionResult<AISuggestionResult> | null>(
    null,
  );
  const [isPending, startTransition] = useTransition();

  function loadSuggestions() {
    startTransition(async () => {
      const data = await getAISuggestions();
      setResult(data);
    });
  }

  const placeholder = result?.data ?? {
    explanation:
      "Get a personalized review of your portfolio strengths and next steps. Uses one of your monthly AI talks.",
    strengths: [],
    gaps: [],
    nextSteps: [],
  };

  return (
    <Card>
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h2 className="text-lg font-semibold text-slate-900">
            {compact ? "AI Portfolio Review" : "Portfolio Mentorship & Guidance"}
          </h2>
          <p className="mt-1 text-xs text-slate-500">
            {result?.source === "ai"
              ? `Personalized advice generated by ${result.tierLabel ?? "AI"}`
              : "Generate customized portfolio advice, or talk directly with your advisor"}
          </p>
        </div>
        {result && (
          <Button
            type="button"
            variant="outline"
            size="sm"
            onClick={loadSuggestions}
            disabled={isPending}
          >
            {isPending ? "Reviewing…" : "Refresh review"}
          </Button>
        )}
      </div>

      <div className="mt-4">
        <AITokenBadge />
      </div>

      {!result && (
        <div className="mt-4 flex flex-wrap gap-2">
          <Button type="button" onClick={loadSuggestions} disabled={isPending}>
            {isPending ? "Generating review…" : "Get portfolio review"}
          </Button>
          {compact && (
            <Button href="/ai-suggestions" variant="outline">
              Talk with AI advisor
            </Button>
          )}
        </div>
      )}

      {result?.error && (
        <p className="mt-3 text-sm text-amber-700 bg-amber-50 rounded-lg px-3 py-2">
          {result.error}
        </p>
      )}

      {result && (
        <>
          <p className="mt-4 text-sm leading-relaxed text-slate-700">
            {placeholder.explanation}
          </p>

          {placeholder.strengths && placeholder.strengths.length > 0 && (
            <div className="mt-4 rounded-xl bg-emerald-50/60 border border-emerald-100 p-3">
              <h3 className="text-xs font-semibold uppercase tracking-wider text-emerald-800">
                Key Strengths
              </h3>
              <ul className="mt-1.5 list-disc pl-4 text-xs text-emerald-900 space-y-1">
                {placeholder.strengths.map((s, i) => (
                  <li key={i}>{s}</li>
                ))}
              </ul>
            </div>
          )}

          {placeholder.gaps && placeholder.gaps.length > 0 && (
            <div className="mt-3 rounded-xl bg-amber-50/60 border border-amber-100 p-3">
              <h3 className="text-xs font-semibold uppercase tracking-wider text-amber-800">
                Portfolio Gaps to Address
              </h3>
              <ul className="mt-1.5 list-disc pl-4 text-xs text-amber-900 space-y-1">
                {placeholder.gaps.map((g, i) => (
                  <li key={i}>{g}</li>
                ))}
              </ul>
            </div>
          )}

          {placeholder.nextSteps.length > 0 && (
            <div className="mt-4">
              <h3 className="text-sm font-semibold text-slate-900">
                Recommended Next Steps
              </h3>
              <ol className="mt-2 list-decimal space-y-1 pl-5 text-sm text-slate-600">
                {placeholder.nextSteps.map((step, idx) => (
                  <li key={idx}>{step}</li>
                ))}
              </ol>
            </div>
          )}
        </>
      )}

      {compact && result && (
        <div className="mt-4 pt-3 border-t border-slate-100 flex items-center justify-between">
          <Link
            href="/ai-suggestions"
            className="text-sm font-medium text-indigo-600 hover:text-indigo-700"
          >
            Open interactive AI advisor chat
          </Link>
        </div>
      )}
    </Card>
  );
}
