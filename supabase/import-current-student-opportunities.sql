-- The SQL Editor is administrator-only. These transaction-local claims let the
-- existing workflow trigger accept this administrator import.
select set_config('request.jwt.claims', '{"role":"service_role"}', true);
select set_config('request.jwt.claim.role', 'service_role', true);

-- Change this email only. The account must already exist in public.profiles.
do $$
declare
  owner_id uuid;
begin
  select id
    into owner_id
  from public.profiles
  where lower(email) = lower('REPLACE-WITH-YOUR-ACCOUNT-EMAIL@example.com');

  if owner_id is null then
    raise exception 'No profile was found for that email. Create the account first, then replace the email in this script.';
  end if;

  perform set_config('opportunityhub.import_owner_id', owner_id::text, true);
end;
$$;

-- Keep old listings for history, but remove records with a passed deadline from
-- the student feed. This affects only listings owned by the selected account.
